using System.Globalization;
using System.Text;
using System.Xml.Linq;

namespace MicroDCS.JobControl.TableGen;

/// <summary>Reads the transitions of a Job Control V2 NodeSet2 and writes them as a C# table (D-34).</summary>
internal static class TransitionTableGenerator
{
    private const string TransitionTypeId = "i=2310";

    /// <summary>Generates the source text of the table.</summary>
    /// <param name="nodeSet">The NodeSet2 document.</param>
    /// <returns>The C# source, with line feeds as line endings.</returns>
    public static string Generate(Stream nodeSet)
    {
        var root = XDocument.Load(nodeSet).Root!;
        var ua = root.GetDefaultNamespace();
        var nodes = root.Elements().Where(e => e.Attribute("NodeId") is not null).ToDictionary(e => e.Attribute("NodeId")!.Value);
        var rows = nodes.Values
            .Where(node => IsTransition(node, ua))
            .Select(transition => ToRow(transition, nodes, ua))
            .OrderBy(row => row.Machine, StringComparer.Ordinal)
            .ThenBy(row => row.Number)
            .ToList();

        var source = new StringBuilder();
        source.Append("// <auto-generated>\n")
            .Append("// Generated by tools/MicroDCS.JobControl.TableGen from NodeSets/Opc.Ua.ISA95.JobControl.V2.NodeSet2.xml. Do not edit.\n")
            .Append("// A test regenerates this file and compares it (D-34).\n")
            .Append("// </auto-generated>\n")
            .Append("using System.Collections.Immutable;\n\n")
            .Append("namespace MicroDCS.JobControl.StateMachine;\n\n")
            .Append("internal static class JobControlV2Transitions\n{\n")
            .Append("    public static ImmutableArray<NodeSetTransition> All { get; } =\n    [\n");
        foreach (var row in rows)
        {
            source.Append(CultureInfo.InvariantCulture, $"        new(\"{row.Machine}\", \"{row.Name}\", {row.Number}, \"{row.From}\", \"{row.To}\", {Literal(row.Cause)}, {Literal(row.Effect)}),\n");
        }

        source.Append("    ];\n}\n");
        return source.ToString();
    }

    private static bool IsTransition(XElement node, XNamespace ua) =>
        node.Element(ua + "References") is not null
        && References(node, "HasTypeDefinition", ua).Contains(TransitionTypeId)
        && References(node, "FromState", ua).Count != 0;

    private static Row ToRow(XElement transition, Dictionary<string, XElement> nodes, XNamespace ua)
    {
        var id = transition.Attribute("NodeId")!.Value;
        var number = nodes.Values.Single(n => n.Attribute("ParentNodeId")?.Value == id && n.Attribute("BrowseName")?.Value == "TransitionNumber");
        return new Row(
            BrowseName(nodes[transition.Attribute("ParentNodeId")!.Value]),
            BrowseName(transition),
            uint.Parse(number.Descendants().Last().Value, CultureInfo.InvariantCulture),
            BrowseName(nodes[References(transition, "FromState", ua).Single()]),
            BrowseName(nodes[References(transition, "ToState", ua).Single()]),
            Target(transition, "HasCause", nodes, ua),
            Target(transition, "HasEffect", nodes, ua));
    }

    private static string? Target(XElement transition, string referenceType, Dictionary<string, XElement> nodes, XNamespace ua) =>
        References(transition, referenceType, ua).SingleOrDefault() is { } id ? BrowseName(nodes[id]) : null;

    private static List<string> References(XElement node, string referenceType, XNamespace ua) =>
    [
        .. node.Element(ua + "References")!.Elements(ua + "Reference")
            .Where(r => r.Attribute("ReferenceType")!.Value == referenceType && r.Attribute("IsForward")?.Value != "false")
            .Select(r => r.Value),
    ];

    private static string BrowseName(XElement node)
    {
        var name = node.Attribute("BrowseName")!.Value;
        return name[(name.IndexOf(':', StringComparison.Ordinal) + 1)..];
    }

    private static string Literal(string? value) => value is null ? "null" : $"\"{value}\"";

    private sealed record Row(string Machine, string Name, uint Number, string From, string To, string? Cause, string? Effect);
}
