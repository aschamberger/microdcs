using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace MicroDCS.Generators;

/// <summary>
/// Emits payload descriptors for <c>[CloudEventType]</c> records and the <c>IDescribedProcessor</c> implementation of
/// <c>[Processor]</c> classes (D-35). Diagnostics are reported from the same pass.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class MicroDcsGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax { AttributeLists.Count: > 0 },
                static (ctx, ct) => ctx.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)ctx.Node, ct) as INamedTypeSymbol)
            .Where(static symbol => symbol is not null)
            .Collect();

        context.RegisterSourceOutput(candidates, static (output, symbols) => GenerateCode(output, symbols));
    }

    private static void GenerateCode(SourceProductionContext output, ImmutableArray<INamedTypeSymbol?> symbols)
    {
        var types = symbols.Where(s => s is not null).Select(s => s!).Distinct(SymbolEqualityComparer.Default).Cast<INamedTypeSymbol>().ToList();
        var payloads = new PayloadAnalyzer(types, output.ReportDiagnostic);

        var processors = new List<(INamedTypeSymbol Type, string Source)>();
        foreach (var type in types.Where(t => PayloadAnalyzer.Find(t, Names.Processor) is not null))
        {
            var source = ProcessorEmitter.Emit(type, payloads, output.ReportDiagnostic);
            if (source is not null)
            {
                processors.Add((type, source));
            }
        }

        if (payloads.Payloads.Any())
        {
            output.AddSource("MicroDcsPayloads.g.cs", SourceText.From(EmitPayloads(payloads.Payloads), Encoding.UTF8));
        }

        foreach (var (type, source) in processors)
        {
            output.AddSource(type.ToDisplayString().Replace('.', '_') + ".g.cs", SourceText.From(source, Encoding.UTF8));
        }
    }

    private static string EmitPayloads(IEnumerable<PayloadInfo> payloads)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("internal static class MicroDcsPayloads");
        sb.AppendLine("{");
        foreach (var payload in payloads)
        {
            var type = payload.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (payload.ContextAccess is null)
            {
                sb.AppendLine($"    public static readonly {Names.OpcUaJsonDescriptor}<{type}> {payload.FieldName} = new({Literal(payload.TypeId)}, {(payload.Schema is null ? "null" : Literal(payload.Schema))});");
                continue;
            }

            sb.AppendLine($"    public static readonly global::MicroDCS.Core.Messaging.JsonPayloadDescriptor<{type}> {payload.FieldName} = new(");
            sb.AppendLine($"        {Literal(payload.TypeId)}, {(payload.Schema is null ? "null" : Literal(payload.Schema))}, {payload.ContextAccess},");
            sb.Append("        " + CarriedArray(type, payload.Carried));
            sb.AppendLine(");");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string CarriedArray(string type, List<CarriedInfo> carried)
    {
        var element = "global::MicroDCS.Core.Messaging.CarriedField<" + type + ">";
        if (carried.Count == 0)
        {
            return "global::System.Collections.Immutable.ImmutableArray<" + element + ">.Empty";
        }

        var items = string.Join(", ", carried.Select(c =>
            $"new {element}({Literal(c.AttributeName)}, p => p.{c.PropertyName}, (p, v) => p with {{ {c.PropertyName} = v }})"));
        return "global::System.Collections.Immutable.ImmutableArray.Create<" + element + ">(" + items + ")";
    }

    internal static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);
}
